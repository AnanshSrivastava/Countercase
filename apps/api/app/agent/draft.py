"""F5/F6 draft engine. One code path for memory on and off: only the recall step differs (demo fairness).

Claims are generated by a pluggable ClaimGenerator (default: deterministic templates over verified evidence;
an LLM generator can be swapped in later). Whatever generates them, the validator filters before the letter is built.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from datetime import timedelta

from .beliefs import DISMISSED, compute_beliefs, load_cases
from .classifier import build_checklist
from .memory import MemoryRef, MemoryStore
from .rules import strong_evidence
from .scorer import DEFAULT_PRIOR, advise, win_probability
from .validator import render_letter, validate_claims

ClaimGenerator = Callable[[dict, list[dict], list[MemoryRef]], list[dict]]

_PREFIX = {
    "order_receipt": "Order record",
    "delivery_proof": "Delivery record",
    "tracking": "Shipping record",
    "prior_orders": "Order history",
    "ip_device": "Device and IP record",
    "customer_message": "Customer communication",
    "refund_policy": "Policy shown at checkout",
    "seller_upload": "Seller-provided document",
}


def template_claims(dispute: dict, evidence: list[dict], memory: list[MemoryRef]) -> list[dict]:
    """One claim per verified evidence item, quoting the evidence summary. Never invents facts."""
    return [
        {"text": f"{_PREFIX.get(e['type'], 'Record')}: {e['summary']}.", "evidence_id": e["id"]}
        for e in evidence
        if e.get("verified") and e["type"] in _PREFIX
    ]


def _dict(m: MemoryRef) -> dict:
    return {
        "id": m.id,
        "kind": m.kind,
        "text": m.text,
        "confidence": m.confidence,
        "n_supporting": m.n_supporting,
        "event_date": m.event_date.isoformat() if m.event_date else None,
        "used": m.used,
        "why": m.why,
        "editable": m.editable,
    }


RECENT_DAYS = 60


def _history(
    cases: list[MemoryRef], category: str, evidence_types: set[str], courier: str | None = None
) -> dict:
    """Counts from this seller's recalled cases. `cohort` = same reason AND same key evidence;
    the cohort's prior is the category-level rate, which in turn is shrunk toward the shared rate."""
    mine = strong_evidence(evidence_types, category)
    reason = f"reason:{category}"
    cat = [m for m in cases if m.kind == "case" and reason in m.tags]
    cohort = [
        m
        for m in cat
        if strong_evidence(
            {t.split(":", 1)[1] for t in m.tags if t.startswith("evidence:")}, category
        )
        == mine
    ]

    def wl(ms: list[MemoryRef]) -> tuple[int, int]:
        return (sum("outcome:won" in m.tags for m in ms), sum("outcome:lost" in m.tags for m in ms))

    # Third level: the same cohort handled by the same courier in the recent window (couriers go bad over time).
    dates = [m.event_date for m in cases if m.event_date]
    recent: list[MemoryRef] = []
    if courier and dates:
        since = max(dates) - timedelta(days=RECENT_DAYS)
        recent = [
            m
            for m in cohort
            if f"courier:{courier}" in m.tags and m.event_date and m.event_date >= since
        ]
    return {"cat": wl(cat), "cohort": wl(cohort), "courier": wl(recent)}


def customer_probably_right(category: str, evidence: list[dict]) -> bool:
    """Honest advice: the customer is probably right. Only fires on verified evidence, never on seller notes."""
    verified = [e for e in evidence if e.get("verified")]
    if category == "not_received":
        delivered = any(e["type"] == "delivery_proof" for e in verified)
        returned = any(
            e["type"] == "tracking"
            and re.search(r"returned to sender|not delivered", e["summary"], re.I)
            for e in verified
        )
        return returned and not delivered
    if category == "not_as_described":
        # The customer reported damage/defect and the seller's own checkout policy covers it.
        complaint = any(
            e["type"] == "customer_message"
            and re.search(
                r"damaged|cracked|broken|defective|faulty|wrong item|not working",
                e["summary"],
                re.I,
            )
            for e in verified
        )
        policy_covers = any(
            e["type"] == "refund_policy" and re.search(r"refund|replace", e["summary"], re.I)
            for e in verified
        )
        return complaint and policy_covers
    return False


def _min_amount(memory: list[MemoryRef]) -> int:
    """Directive like 'Never fight disputes under 500' -> 50000 minor units."""
    for m in memory:
        if m.kind == "directive":
            hit = re.search(r"never fight.*?under\D*(\d+)", m.text, re.I)
            if hit:
                return int(hit.group(1)) * 100
    return 0


def build_draft(
    dispute: dict,
    evidence: list[dict],
    store: MemoryStore,
    *,
    memory_on: bool,
    generate_claims: ClaimGenerator = template_claims,
    claim_looks_valid: bool = False,
) -> dict:
    category = dispute["category"]
    memory: list[MemoryRef] = []
    if memory_on:
        tags = [
            f"reason:{category}",
            f"courier:{dispute.get('courier')}",
            f"customer:{dispute.get('customer_hash')}",
        ]
        memory = store.recall(
            dispute["seller_id"], f"{category} dispute {dispute.get('product_sku', '')}", tags=tags
        )
        # Customer history is looked up on its own so a repeat disputer is never crowded out by generic cases.
        cust_tag = f"customer:{dispute.get('customer_hash')}"
        seen = {m.id for m in memory}
        for m in store.recall(
            dispute["seller_id"], "this customer's earlier disputes", tags=[cust_tag]
        ):
            if m.id not in seen and cust_tag in m.tags:
                m.why = "Same customer disputed before"
                memory.append(m)
        for m in memory:
            m.why = m.why or (
                "Seller directive applied to every draft"
                if m.kind == "directive"
                else "Matches this dispute's reason, courier or customer"
            )

    ev_types = {e["type"] for e in evidence if e.get("verified")}
    cases = load_cases(store, dispute["seller_id"]) if memory_on else []
    h = _history(cases, category, ev_types, dispute.get("courier"))
    for bel in compute_beliefs(cases, DISMISSED.get(dispute["seller_id"], set())):
        if bel.key.endswith(f":{category}") or bel.key == f"courier:{dispute.get('courier')}":
            memory.append(bel.as_memory_ref())
    (cw, cl), (w, lo) = h["cat"], h["cohort"]
    cat_rate, _ = win_probability(cw, cl, DEFAULT_PRIOR.get(category, 0.35))
    prior_for_cohort = cat_rate
    (rw, rl) = h["courier"]
    if (
        rw + rl >= 3
    ):  # enough recent cases with this courier: it becomes the most specific evidence we have
        prior_for_cohort, _ = win_probability(w, lo, cat_rate)
        w, lo = rw, rl
    advice = advise(
        category=category,
        amount=dispute["amount"],
        currency=dispute["currency"],
        wins=w,
        losses=lo,
        prior_rate=prior_for_cohort,
        claim_looks_valid=claim_looks_valid or customer_probably_right(category, evidence),
        min_amount=_min_amount(memory),
    )

    # Honest advice: when the customer is probably right we do not draft a rebuttal at all.
    no_rebuttal = advice.action == "accept" and (
        claim_looks_valid or customer_probably_right(category, evidence)
    )
    validation = validate_claims(
        [] if no_rebuttal else generate_claims(dispute, evidence, memory), evidence
    )
    return {
        "dispute_id": dispute["id"],
        "memory_mode": "on" if memory_on else "off",
        "advice": {
            "action": advice.action,
            "win_probability": advice.win_probability,
            "interval": list(advice.interval),
            "n_cases": advice.n_cases,
            "basis": advice.basis,
            "amount_vs_cost": advice.amount_vs_cost,
            "rationale": advice.rationale,
        },
        "checklist": build_checklist(category, evidence),
        "claims": validation.valid,
        "rejected_claims": validation.rejected,
        "letter_md": render_letter(validation.valid, evidence) if validation.valid else "",
        "memory": [_dict(m) for m in memory],
        "cost": {
            "input_tokens": 0,
            "output_tokens": 0,
            "recall_calls": 3 if memory_on else 0,
            "usd": 0.0,
        },
    }
